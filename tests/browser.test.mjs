async function axe(page) {
  await page.addScriptTag({ path: axePath });
  const violations = await page.evaluate(async () => {
    const result = await window.axe.run({
      runOnly: { type: "tag", values: ["wcag2a", "wcag2aa", "wcag21a", "wcag21aa", "wcag22aa"] },
    });
    return result.violations.map(({ id, nodes }) => ({ id, targets: nodes.map(({ target }) => target) }));
  });
  assert.deepEqual(violations, []);
}

/** The script chunks a page's own HTML loads; any other chunk is loaded lazily. */
async function initialChunks(route) {
  const html = await (await fetch(website(route))).text();
  return new Set(html.match(/\/_next\/static\/chunks\/[^"'\s]+?\.js/g));
}

/** Tab from `from` until the Orin disclosure button; every stop on the way. */
async function tabStopsToDisclosure(page, from) {
  await from.focus();
  const stops = [];
  for (let step = 0; step < 20; step++) {
    await page.keyboard.press("Tab");
    const stop = await page.evaluate(() => {
      const element = document.activeElement;
      return {
        disclosure: element?.getAttribute("aria-controls") === "orin-analysis",
        inAnalysis: Boolean(element?.closest("#orin-analysis")),
        reportLink: Boolean(element?.matches("#orin-demo-result a") && !element.closest("#orin-analysis")),
      };
    });
    if (stop.disclosure) return stops;
    stops.push(stop);
  }
  throw new Error("Tab never reached the disclosure button");
}

/**
 * Opens "View chart data" once the revenue chart above it has drawn. The chart loads lazily,
 * and while its code downloads its placeholder collapses, which moves the summary by about
 * 210px; a click during that move can miss.
 */
async function openChartData(scope) {
  const summary = scope.getByText("View chart data", { exact: true });
  await summary.scrollIntoViewIfNeeded();
  await scope.locator(".recharts-surface").first().waitFor();
  await summary.click();
}

/** Accessible names Chromium exposes in its accessibility tree (ignored nodes left out). */
async function exposedNames(page) {
  const cdp = await page.context().newCDPSession(page);
  try {
    const { nodes } = await cdp.send("Accessibility.getFullAXTree");
    return new Set(nodes.filter((node) => !node.ignored && node.name?.value).map((node) => node.name.value));
  } finally {
    await cdp.detach();
  }
}

/**
 * The first Ctrl+K on a fresh page, typed into at once: the menu's code is held back (every
 * lazily loaded chunk waits until released), so the keys arrive before the menu exists.
 */
async function firstShortcut(context) {
  const page = await context.newPage();
  page.setDefaultTimeout(8500);
  try {
    const initial = await initialChunks("/");
    let release;
    const released = new Promise((resolve) => (release = resolve));
    await page.route(
      (url) =>
        url.pathname.startsWith("/_next/static/chunks/") &&
        url.pathname.endsWith(".js") &&
        !initial.has(url.pathname),
      async (route) => {
        await released;
        await route.continue().catch(() => {});
      },
    );
    // Report a non-Apple platform: the trigger's label then changes from the server's "⌘K" to
    // "Ctrl K" in the render that follows hydration's effects, so the shortcut is listened for.
    await page.addInitScript(() =>
      Object.defineProperty(Navigator.prototype, "platform", { configurable: true, get: () => "Win32" }),
    );
    await page.goto(website("/"), { waitUntil: "load" });
    const trigger = menuButton(page);
    await page.waitForFunction(
      () =>
        document.querySelector('button[aria-haspopup="dialog"]')?.getAttribute("aria-label") ===
        "Ctrl K – Open menu",
    );

    await page.keyboard.press("Control+K");
    await page.keyboard.type("open resx");
    await page.keyboard.press("Backspace");
    assert.equal(await page.locator("[data-command-menu]").count(), 0, "The menu's code is still held");
    assert.equal(await trigger.getAttribute("aria-expanded"), "true");
    assert.equal(await page.evaluate(() => window.scrollY), 0, "No typed key reached the page");

    release();
    const search = menu(page).getByRole("combobox");
    await search.waitFor();
    await page.waitForFunction(() => document.activeElement?.getAttribute("role") === "combobox");
    assert.equal(await search.inputValue(), "open res");
    await page.keyboard.type("ume");
    assert.equal(await search.inputValue(), "open resume");
    await page.keyboard.press("Escape");
    await menu(page).waitFor({ state: "hidden" });
    await page.waitForFunction(
      () => document.activeElement === document.querySelector('button[aria-haspopup="dialog"]'),
    );
  } finally {
    await page.close();
  }
}

async function menuFocus(page) {
  await page.setViewportSize({ width: 1440, height: 900 });
  await goto(page, "/");
  const trigger = menuButton(page);
  for (const opener of ["click", "shortcut"]) {
    for (const closer of ["Escape", "close button", "outside"]) {
      const prior =
        opener === "shortcut"
          ? page.getByRole("navigation", { name: "Primary" }).getByRole("link", { name: "Info" })
          : trigger;
      await prior.focus();
      if (opener === "shortcut") await page.keyboard.press("Control+k");
      else await trigger.click();
      const dialog = menu(page);
      await dialog.waitFor();
      assert.equal(
        await page.locator('button[aria-haspopup="dialog"]').getAttribute("aria-expanded"),
        "true",
      );
      await page.waitForFunction(() => document.activeElement?.getAttribute("role") === "combobox");
      for (const key of ["Tab", "Tab", "Shift+Tab"]) {
        await page.keyboard.press(key);
        // Focus guards wrap the keyboard cycle on the following animation frame.
        await page.waitForFunction(() => Boolean(document.activeElement?.closest('[role="dialog"]')));
      }
      if (closer === "Escape") await page.keyboard.press("Escape");
      if (closer === "close button") await dialog.getByRole("button", { name: "Close menu" }).click();
      if (closer === "outside") await page.mouse.click(5, 5);
      await dialog.waitFor({ state: "hidden" });
      await prior.evaluate(
        (element) =>
          new Promise((resolve, reject) => {
            requestAnimationFrame(() =>
              element === document.activeElement
                ? resolve()
                : reject(new Error("Focus did not return to opener")),
            );
          }),
      );
    }
  }
  await trigger.click();
  const dialog = menu(page);
  await dialog.getByRole("combobox").fill("Contact");
  await page.keyboard.press("ArrowDown");
  await dialog.getByRole("option", { name: "Contact", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.waitForFunction(() => Boolean(document.activeElement?.closest("#contact")));
  await trigger.click();
  await dialog.getByRole("combobox").fill("Business-Software");
  await page.keyboard.press("Enter");
  await page.waitForURL(website("/work/business-software"));
  await dialog.waitFor({ state: "hidden" });
}

async function orinPreview(page, engine) {
  await page.setViewportSize({ width: 1440, height: 900 });
  await goto(page, "/work/orin");
  const result = panel(page);
  const analysis = page.locator("#orin-analysis");
  const disclosure = page.locator('button[aria-controls="orin-analysis"]');
  const report = result.getByRole("link", { name: /Read the official report/ });
  const health = result.getByRole("region", { name: "Business health" });
  const chartData = analysis.getByText("View chart data", { exact: true });
  const inertIs = (value) =>
    page.waitForFunction((v) => document.getElementById("orin-analysis")?.inert === v, value);
  const lastSample = page.getByRole("group", { name: "Sample tickers" }).getByRole("button").last();
  // Safari's default (WebKit here): Tab skips links, so only buttons and fields are stops.
  const tabsToLinks = engine !== "webkit";

  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 900 });

    // Collapsed: everything below the health card is faded out, inert and out of the Tab order.
    await inertIs(true);
    assert.equal(await disclosure.getAttribute("aria-expanded"), "false");
    assert.equal(squash(await disclosure.innerText()), "Show the full analysis");
    for (const kept of [report, health]) {
      assert.equal(await kept.evaluate((element) => element.closest("[inert]")), null);
    }
    await report.focus();
    await waitFocused(report);
    assert.equal(
      await chartData.evaluate((element) => {
        element.focus();
        return element === document.activeElement;
      }),
      false,
      "Collapsed controls cannot take focus",
    );
    let stops = await tabStopsToDisclosure(page, lastSample);
    assert.ok(!stops.some((stop) => stop.inAnalysis), "Tab skips the collapsed part");
    if (tabsToLinks)
      assert.ok(
        stops.some((stop) => stop.reportLink),
        "Tab reaches the header link",
      );
    if (engine === "chromium") {
      const names = await exposedNames(page);
      assert.ok(names.has("Business health") && !names.has("What most people miss"));
    }

    // Expanded: the whole analysis is reachable.
    await disclosure.click();
    await inertIs(false);
    assert.equal(await disclosure.getAttribute("aria-expanded"), "true");
    assert.equal(squash(await disclosure.innerText()), "Show less");
    stops = await tabStopsToDisclosure(page, lastSample);
    assert.ok(
      stops.some((stop) => stop.inAnalysis),
      "Tab reaches the analysis",
    );
    if (engine === "chromium") assert.ok((await exposedNames(page)).has("What most people miss"));

    // "Show less" collapses it again (from the keyboard: the lazy chart above can still move it).
    await page.getByRole("button", { name: "Show less" }).focus();
    await page.keyboard.press("Enter");
    await inertIs(true);
    assert.equal(await disclosure.getAttribute("aria-expanded"), "false");
    assert.notEqual(await result.evaluate((element) => getComputedStyle(element).maxHeight), "none");
  }

  // Every sample keeps its header and health card in full view (above the fade, so inside the
  // clip too) at both review widths. Below about 350px the fade reaches the health card.
  for (const { result: data } of samples) {
    await page.getByRole("button", { name: data.snapshot.ticker, exact: true }).click();
    await result.getByRole("heading", { name: data.snapshot.companyName, exact: true }).waitFor();
    await inertIs(true);
    for (const width of [390, 1440]) {
      await page.setViewportSize({ width, height: 900 });
      const clearance = await health.evaluate(
        (element) =>
          document.querySelector(".demo-expand").getBoundingClientRect().top -
          element.getBoundingClientRect().bottom,
      );
      assert.ok(clearance >= 0, `${data.snapshot.ticker} health card above the fade at ${width}`);
    }
  }
}

async function heroMotion(page, motion) {
  await page.setViewportSize({ width: 1440, height: 900 });
  await goto(page, "/");
  const stage = page.locator(".hero-stage");
  const motionOk = await page.evaluate(() => document.documentElement.classList.contains("motion-ok"));
  if (motion === "reduce") {
    assert.equal(motionOk, false, "No scroll-linked motion with reduced motion");
    await page.evaluate(() => window.scrollTo(0, 300));
    await page.waitForFunction(() => window.scrollY >= 300);
    // The frame stays inset: its geometry never follows the scroll position.
    assert.equal(
      await stage.evaluate((element) => getComputedStyle(element).getPropertyValue("--q").trim()),
      "1",
    );
  } else {
    assert.equal(motionOk, true, "html.motion-ok is set before first paint");
    // --p is the zoom's progress (0 → 1), written from the scroll position.
    assert.equal(await stage.evaluate((element) => Number(element.style.getPropertyValue("--p") || 0)), 0);
    await page.evaluate(() => window.scrollTo(0, 300));
    await page.waitForFunction(
      () => Number(document.querySelector(".hero-stage").style.getPropertyValue("--p")) > 0,
    );
  }
  await page.evaluate(() => window.scrollTo(0, 0));
}

